-- Stage A artifact. Apply only to a reviewed EMPTY project, inside one transaction with rls.sql.
-- Existing table names deliberately cause an error; never silently accept incompatible tables.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE public.profiles (
id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
display_name text DEFAULT '',
created_at timestamptz DEFAULT now(),
updated_at timestamptz DEFAULT now()
);

CREATE TABLE public.exercise_library (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name text UNIQUE NOT NULL,
category text DEFAULT '', equipment text DEFAULT '', aliases text DEFAULT '',
created_at timestamptz DEFAULT now()
);

CREATE TABLE public.members (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
coach_id uuid NOT NULL REFERENCES auth.users(id),
name text NOT NULL,
created_at timestamptz DEFAULT now(),
remaining_lessons integer DEFAULT 10 CHECK (remaining_lessons >= 0),
goal text DEFAULT '', last_training_date date, ai_reminder text DEFAULT '',
avatar_emoji text DEFAULT '', phone text DEFAULT '', note text DEFAULT '',
UNIQUE(id, coach_id)
);

CREATE TABLE public.body_measurements (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
coach_id uuid NOT NULL REFERENCES auth.users(id), member_id bigint NOT NULL,
record_date date NOT NULL,
height text DEFAULT '', weight text DEFAULT '', body_fat text DEFAULT '',
waist text DEFAULT '', hip text DEFAULT '', note text DEFAULT '',
created_at timestamptz DEFAULT now(),
FOREIGN KEY(member_id, coach_id) REFERENCES public.members(id, coach_id) ON DELETE CASCADE
);

CREATE TABLE public.training_sessions (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
coach_id uuid NOT NULL REFERENCES auth.users(id), member_id bigint NOT NULL,
training_date date NOT NULL, member_feedback text DEFAULT '', coach_note text DEFAULT '',
raw_paste_text text DEFAULT '', created_at timestamptz DEFAULT now(),
UNIQUE(id, member_id, coach_id),
FOREIGN KEY(member_id, coach_id) REFERENCES public.members(id, coach_id) ON DELETE CASCADE
);

CREATE TABLE public.training_session_exercises (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
session_id bigint NOT NULL REFERENCES public.training_sessions(id) ON DELETE CASCADE,
exercise_id bigint REFERENCES public.exercise_library(id), exercise_name text NOT NULL,
weight text DEFAULT '', sets text DEFAULT '', reps text DEFAULT '', rpe text DEFAULT '',
note text DEFAULT '', sort_order integer DEFAULT 0
);

CREATE TABLE public.ai_analysis_reports (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
coach_id uuid NOT NULL REFERENCES auth.users(id), member_id bigint NOT NULL,
report_date date NOT NULL, report_markdown text NOT NULL, input_summary text DEFAULT '',
created_at timestamptz DEFAULT now(), UNIQUE(id, member_id, coach_id),
FOREIGN KEY(member_id, coach_id) REFERENCES public.members(id, coach_id) ON DELETE CASCADE
);

CREATE TABLE public.training_plans (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
coach_id uuid NOT NULL REFERENCES auth.users(id), member_id bigint NOT NULL,
plan_date date NOT NULL, status text NOT NULL DEFAULT 'confirmed' CHECK (status IN ('draft','confirmed','used')),
source_analysis_report_id bigint, plan_goal text DEFAULT '', coach_note text DEFAULT '', raw_ai_plan text DEFAULT '',
created_at timestamptz DEFAULT now(), updated_at timestamptz DEFAULT now(),
UNIQUE(id, member_id, coach_id),
FOREIGN KEY(member_id, coach_id) REFERENCES public.members(id, coach_id) ON DELETE CASCADE,
FOREIGN KEY(source_analysis_report_id, member_id, coach_id) REFERENCES public.ai_analysis_reports(id, member_id, coach_id)
);

CREATE TABLE public.training_plan_exercises (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
plan_id bigint NOT NULL REFERENCES public.training_plans(id) ON DELETE CASCADE,
exercise_id bigint REFERENCES public.exercise_library(id), exercise_name text NOT NULL,
target_weight text DEFAULT '', sets text DEFAULT '', reps text DEFAULT '', target_rpe text DEFAULT '',
note text DEFAULT '', sort_order integer DEFAULT 0
);

CREATE TABLE public.appointments (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
coach_id uuid NOT NULL REFERENCES auth.users(id), member_id bigint NOT NULL,
appointment_date date NOT NULL, start_time time NOT NULL, end_time time NOT NULL,
status text NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled','completed','cancelled')),
note text DEFAULT '', training_plan_id bigint, training_session_id bigint,
created_at timestamptz DEFAULT now(), updated_at timestamptz DEFAULT now(),
CHECK(start_time < end_time),
FOREIGN KEY(member_id, coach_id) REFERENCES public.members(id, coach_id) ON DELETE CASCADE,
FOREIGN KEY(training_plan_id, member_id, coach_id) REFERENCES public.training_plans(id, member_id, coach_id),
FOREIGN KEY(training_session_id, member_id, coach_id) REFERENCES public.training_sessions(id, member_id, coach_id),
EXCLUDE USING gist (coach_id WITH =, tsrange(appointment_date + start_time, appointment_date + end_time, '[)') WITH &&) WHERE (status <> 'cancelled')
);

CREATE TABLE public.training_session_photos (
id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
coach_id uuid NOT NULL REFERENCES auth.users(id), member_id bigint NOT NULL, session_id bigint NOT NULL,
bucket_name text NOT NULL DEFAULT 'training-photos' CHECK(bucket_name = 'training-photos'),
object_path text UNIQUE NOT NULL,
original_filename text DEFAULT '', caption text DEFAULT '', created_at timestamptz DEFAULT now(),
CHECK(split_part(object_path,'/',1) = coach_id::text AND split_part(object_path,'/',2) = member_id::text AND split_part(object_path,'/',3) = session_id::text AND array_length(string_to_array(object_path,'/'),1) = 4 AND split_part(object_path,'/',4) <> '' AND object_path !~ '(^|/)[.][.]?(/|$)'),
FOREIGN KEY(member_id, coach_id) REFERENCES public.members(id, coach_id) ON DELETE CASCADE,
FOREIGN KEY(session_id, member_id, coach_id) REFERENCES public.training_sessions(id, member_id, coach_id) ON DELETE CASCADE
);
